"""One source for every host's guidance. Generates the Gemini CLI extension.

WHY GENERATED AND NOT WRITTEN TWICE. Two hosts need the same guidance: Claude
Code reads `.claude/skills/contextlift/SKILL.md`, Gemini CLI reads a `GEMINI.md`
inside an extension directory. Writing both by hand is a rule written twice,
and this project already paid for that once -- the DuckDB backend note records
it: "two backends drifting apart is how a rule ends up written twice and one
copy goes stale, which is how a truncated result was once compared as if it
were whole."

Drift in a guidance file is worse than drift in a backend. These files are
where the safety rules live: that the guards are not the host's to waive, that
the reserved half must not be read to decide what to write, that a second
model sees the workspace. A stale copy of a safety rule is a safety rule that
is not in force on one host, and nobody would notice which.

So SKILL.md is the source, the extension is the output, and
`tests/test_host_guides.py` fails if the committed output is not what this
script writes.

    python scripts/sync_host_guides.py            # write
    python scripts/sync_host_guides.py --check    # exit 1 if it would change

The manifest format is from the Gemini CLI extension reference, read
2026-09-12: github.com/google-gemini/gemini-cli/docs/extensions/reference.md.
`name` and `version` are required; `name` is expected to match the directory
name. `contextFileName` is loaded from the extension directory, which is why
the body is copied there rather than referenced across the repository.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SKILL = ROOT / ".claude" / "skills" / "contextlift" / "SKILL.md"
EXTENSION = ROOT / ".gemini" / "extensions" / "contextlift"

# Said at the top of the generated file, not the bottom. A "do not edit"
# notice below the content is a notice read after the edit.
BANNER = """\
<!-- GENERATED by scripts/sync_host_guides.py from
     .claude/skills/contextlift/SKILL.md -- do not edit this file.
     Edit the skill and re-run the script. `--check` fails on drift, so an
     edit here would be reverted by the next sync and a safety rule would
     quietly differ between hosts. -->

"""

# The one real bypass, stated rather than pretended away. `excludeTools` is
# deliberately NOT used to block it: the reference matches a tool call by
# prefix, so `run_shell_commands(contextlift round --yes)` is defeated by putting
# --yes anywhere else on the line, and a guard that looks enforced and is not
# is worse than a documented rule.
BYPASS_NOTE = """

## The one bypass, and why it is not blocked here

`--yes` skips the typed confirmation. It is the only way to spend money
without a person typing, and it is the user's to ask for, never yours to add.

It cannot be used alone: the command refuses `--yes` without `--budget`, with
"a yes with no ceiling is a blank cheque". So an approved run still has a hard
ceiling on it.

This extension does not put `--yes` in `excludeTools`. That list matches a
tool call by prefix, so a block on `contextlift round --yes` is defeated by
moving the flag further along the line. A guard that looks enforced and is not
is worse than a rule written down.
"""


def read_skill() -> tuple[dict, str]:
    """(frontmatter, body). The frontmatter feeds the manifest."""
    text = SKILL.read_text()
    match = re.match(r"^---\n(.*?)\n---\n(.*)$", text, re.DOTALL)
    if not match:
        raise SystemExit(f"{SKILL} has no YAML frontmatter to read name and "
                         "description from")
    fields: dict[str, str] = {}
    for line in match.group(1).split("\n"):
        if ": " in line and not line.startswith(" "):
            key, value = line.split(": ", 1)
            fields[key.strip()] = value.strip()
    return fields, match.group(2)


def version() -> str:
    """The package version, so the extension and the wheel cannot disagree."""
    text = (ROOT / "pyproject.toml").read_text()
    found = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    return found.group(1) if found else "0.0.0"


def build() -> dict[pathlib.Path, str]:
    fields, body = read_skill()
    name = fields.get("name", "contextlift")
    if name != EXTENSION.name:
        raise SystemExit(f"the skill is named {name!r} but the extension "
                         f"directory is {EXTENSION.name!r}; the reference "
                         "expects them to match")
    manifest = {
        "name": name,
        "version": version(),
        "description": fields.get("description", ""),
        "contextFileName": "GEMINI.md",
    }
    return {
        EXTENSION / "gemini-extension.json":
            json.dumps(manifest, indent=2) + "\n",
        EXTENSION / "GEMINI.md": BANNER + body.rstrip() + BYPASS_NOTE,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if a committed file would change, and write "
                         "nothing. This is what CI and the test run.")
    args = ap.parse_args()

    wanted = build()
    stale = [p for p, text in wanted.items()
             if not p.is_file() or p.read_text() != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
        if stale:
            print("run: python scripts/sync_host_guides.py", file=sys.stderr)
        return 1 if stale else 0

    EXTENSION.mkdir(parents=True, exist_ok=True)
    for path, text in wanted.items():
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}  {len(text)} characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
