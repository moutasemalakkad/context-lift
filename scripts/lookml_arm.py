"""Build a context arm out of a Looker project, and nothing else.

WHY THIS IS A STAGE AND NOT A CHAT COMMAND. The question it exists to answer
is the one every customer asks in the first meeting: "can't you just read my
BI tool?" Answering it needs a spec directory a round can take, and a spec
built by hand in a shell is not reproducible by the person who has to trust
the number.

WHAT IT DELIBERATELY DOES NOT DO. It copies no LookML. The output holds
extracted facts -- metric names, the aggregation Looker's type table implies,
join conditions -- and no source text. `looker-open-source/thelook` ships no
LICENSE file, so its files are read and never vendored; provenance is written
into the output's README instead.

It also adds the empty `schema/` files from the committed thelook spec. Those
carry table NAMES and no descriptions (`description: ""`, `columns: {}`), and
the round refuses to build arms with no tables to name. Without them the
comparison could not run at all; with them it stays fair, because an empty
description is what the estate really had.

    python scripts/lookml_arm.py --lookml DIR --out examples/thelook/lookml-arm
"""
from __future__ import annotations

import argparse
import pathlib
import shutil
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent.parent / "src"))

from context_lift.semantic import read_lookml  # noqa: E402

HERE = pathlib.Path(__file__).resolve().parent.parent
SCHEMA = HERE / "examples" / "thelook" / "spec" / "schema"


def provenance(directory: pathlib.Path) -> str:
    """The source commit, so the arm can be rebuilt exactly. "" if not a repo."""
    try:
        out = subprocess.run(
            ["git", "-C", str(directory), "log", "-1", "--format=%H %ci"],
            capture_output=True, text=True, timeout=20)
        return out.stdout.strip() if out.returncode == 0 else ""
    except Exception:  # noqa: BLE001 -- provenance is a nicety, not a gate
        return ""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lookml", required=True, help="a Looker project directory")
    ap.add_argument("--out", required=True, help="the spec directory to write")
    ap.add_argument("--source-name", default="",
                    help="what to call the source in the README")
    args = ap.parse_args()

    model = read_lookml(args.lookml)
    print(model.summary())

    # A read that failed is not a finding about the project, so it stops here
    # rather than producing a thin arm that looks like a measured result.
    if model.unreadable:
        print(f"\nREFUSED: {len(model.unreadable)} file(s) did not parse. An arm "
              "built from a partial read would be scored as though it were the "
              "whole project.", file=sys.stderr)
        return 1
    if not model.metrics:
        print("\nREFUSED: no metrics were read, so there is no context to test.",
              file=sys.stderr)
        return 1

    out = pathlib.Path(args.out)
    if out.exists():
        shutil.rmtree(out)
    (out / "rules").mkdir(parents=True)
    context = model.to_context()
    (out / "rules" / "00-from-lookml.md").write_text(context)

    if SCHEMA.is_dir():
        shutil.copytree(SCHEMA, out / "schema")
    else:
        print(f"WARNING: {SCHEMA} is missing, so the arm names no tables and "
              "`round` will refuse it", file=sys.stderr)

    source = args.source_name or str(args.lookml)
    sha = provenance(pathlib.Path(args.lookml))
    unresolved = ("\n".join(f"- {n} {c}" for c, n in sorted(
        (v, k) for k, v in model.unresolved.items())) or "- none")
    (out / "README.md").write_text(f"""\
# A context arm read out of a Looker project

Generated by `scripts/lookml_arm.py`. Do not edit by hand: rerun the script.

    source        {source}
    commit        {sha or "not a git checkout"}
    metrics       {len(model.metrics)}, {len(model.documented_metrics)} described
    dimensions    {len(model.dimensions)}, {sum(1 for d in model.dimensions
                                                if d.description)} described
    join paths    {len(model.joins)}
    rules bytes   {len(context)}

No LookML source is copied here. `rules/00-from-lookml.md` holds extracted
facts only: metric names, the aggregation Looker's measure-type table implies,
and join conditions.

`schema/` is copied from `examples/thelook/spec/schema`. Those files are empty
on purpose -- they record that the estate carried no column descriptions -- and
they exist because `round` refuses an arm that names no tables.

Constructs this reader does not resolve:

{unresolved}
""")
    print(f"\nwrote {out}")
    print(f"  rules/00-from-lookml.md  {len(context)} characters")
    print(f"  schema/                  {len(list((out / 'schema').glob('*.yaml')))} "
          "table name(s), no descriptions"
          if (out / "schema").is_dir() else "  schema/  MISSING")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
