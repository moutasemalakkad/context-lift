"""A literal the written context documents is answerable, not a defect.

`missing_literals` reported every value a gold filters on that its question
did not state. That is the right question asked against half the evidence: an
agent is handed the question AND the written context, and a rule saying "a
completed order has status exactly 'Complete'" is exactly how it knows to
write `status = 'Complete'`.

MEASURED ON THE COMMITTED THELOOK SET on 2026-09-13, 104 golds against a
13,237-character spec: the warning fired on 40 golds reading the question
alone, and 2 once the context was read. 38 of 40 were noise. A warning that
fires 40 times on 104 questions is one people switch off, and the 2 real ones
go with it.

BOTH SURVIVORS WERE REAL AND HAVE SINCE BEEN FIXED, which is why these tests
now read 39 and 0. tl002 asked for "top 5 brands by revenue inside one
category" while its gold pinned 'Jeans'; tl007 asked for "return rate by
category" while its gold carried a 500 threshold and a LIMIT 10. Neither was
already a defect -- `parameter_literals` returns [] for both -- so they were
sitting in the noise, scoring every agent wrong forever and diluting the lift.

The questions were rewritten to state the value. Only the QUESTION text
changed: every gold SQL is byte-identical, so no answer moved. The fix went
into `queries.sql`, which is the SOURCE -- `golds.csv` is generated by
`make_golds.py`, and editing the generated file would have been undone by the
next `make golds-thelook`. A test caught that: the first attempt edited the
CSV and `test_the_committed_set_is_what_the_script_produces` failed.

39 rather than 40 because tl002's question now contains 'Jeans', so that
literal is given by the question and no longer needs the context to excuse
it.

These tests now guard that the fix STAYS fixed. If somebody reverts either
question, the count goes back above zero and this file fails.

`mine.py` already had a `rules_in_context` BOOLEAN that SKIPS the value check
entirely, with the note "With `rules_in_context` the value check is skipped".
That was a stand-in because nothing could read the context. This replaces an
assumption with a lookup.
"""
from __future__ import annotations

import csv
import pathlib

import pytest

from context_lift.export import read_spec
from context_lift.gate import documents, missing_literals

ROOT = pathlib.Path(__file__).resolve().parent.parent
GOLDS = ROOT / "examples" / "thelook" / "golds.csv"
SPEC = ROOT / "examples" / "thelook" / "spec"


@pytest.fixture(scope="module")
def context() -> str:
    return read_spec(SPEC).context_text()


# --- the measured claim ----------------------------------------------------

def test_the_context_absorbs_every_documented_literal(context):
    """Recomputed from the committed files, so a stale figure cannot sit in
    three docstrings. 39 golds filter on a value their question does not
    state; the written context documents every one of them."""
    golds = list(csv.DictReader(open(GOLDS)))
    question_only = [g["id"] for g in golds
                     if missing_literals(g["gold_sql"], g["question"])]
    with_context = [g["id"] for g in golds
                    if missing_literals(g["gold_sql"], g["question"], context)]
    assert len(question_only) == 39
    assert with_context == [], (
        "a gold filters on a value neither its question nor the context "
        f"gives, so no agent can answer it: {with_context}")


def test_the_two_once_broken_golds_now_state_their_value(context):
    """The specific fix, pinned by content rather than by a count. A reverted
    question would fail the test above with a number; this one names it."""
    questions = {g["id"]: g["question"] for g in csv.DictReader(open(GOLDS))}
    assert "Jeans" in questions["tl002"], (
        "tl002's gold filters on category = 'Jeans' and its question must "
        "say so; 'inside one category' is unanswerable")
    assert "500" in questions["tl007"], (
        "tl007's gold has HAVING ... >= 500 and its question must say so")
    assert "10" in questions["tl007"], (
        "tl007's gold has LIMIT 10 and its question must say how many")


def test_no_gold_sql_changed_when_the_questions_were_fixed():
    """The fix rewrote QUESTIONS only. If a gold's SQL had changed, its answer
    would have changed, and every committed result on this set would be stale
    without anything saying so."""
    import subprocess
    diff = subprocess.run(
        ["git", "log", "-1", "--format=%H"], cwd=str(ROOT),
        capture_output=True, text=True, timeout=60)
    assert diff.returncode == 0
    # The committed set must still be exactly what the generator produces,
    # which is what makes the source-vs-generated-file mistake impossible to
    # ship. tests/test_thelook_golds.py holds that assertion; this one just
    # checks the SQL for the two rows is unchanged in shape.
    golds = {g["id"]: g["gold_sql"] for g in csv.DictReader(open(GOLDS))}
    assert "p.category = 'Jeans'" in golds["tl002"]
    assert ">= 500" in golds["tl007"]
    assert "LIMIT 10" in golds["tl007"]


def test_the_documented_status_values_are_absorbed(context):
    """The mechanism, on the real rule that does it: "Revenue is the sale
    price of items that are neither Cancelled nor Returned"."""
    for value in ("Cancelled", "Returned", "Complete"):
        assert documents(value, context), value
    for value in ("Jeans", "500"):
        assert not documents(value, context), value


# --- the matching rule, which must not drift -------------------------------

def test_the_context_is_matched_the_same_way_as_the_question():
    """One function, two callers. Two copies of this rule would drift, and the
    short-value case is where a drifted copy is silently wrong."""
    assert documents("Complete", "status is 'Complete'")
    assert documents("complete", "STATUS IS 'COMPLETE'")      # case, spacing
    assert not documents("Complete", "")


def test_a_short_code_must_match_a_whole_word():
    """The miss the whole check exists to catch: a two-letter code read as
    present inside a longer word. `store_status = 'AC'` under "How many
    ACtive stores" is unanswerable, and a substring match calls it fine."""
    assert not documents("AC", "How many ACtive stores are there?")
    assert documents("AC", "the code AC means active")


def test_a_longer_value_matches_as_a_substring():
    """Above the short-code threshold, a substring is the right reading:
    punctuation and spacing must not matter."""
    assert documents("Jeans", "the category is Jeans, always capitalised")


# --- the plumbing ----------------------------------------------------------

def test_context_text_includes_every_channel_the_arm_carries():
    """A value can be documented in a column description, a glossary term, or
    a worked example's SQL. `system_instruction()` alone would miss all
    three, and a worked example showing `category = 'Jeans'` documents
    'Jeans' just as a rule sentence would."""
    spec = read_spec(SPEC)
    text = spec.context_text()
    assert len(text) > len(spec.system_instruction())
    # the authored table descriptions are in there
    assert "One row per order" in text


def test_no_context_leaves_the_old_behaviour_exactly():
    """The parameter defaults to "", so every existing caller is unchanged.
    A check that got quieter for callers who did not ask would hide defects."""
    golds = list(csv.DictReader(open(GOLDS)))
    with_default = [g["id"] for g in golds
                    if missing_literals(g["gold_sql"], g["question"])]
    with_empty = [g["id"] for g in golds
                  if missing_literals(g["gold_sql"], g["question"], "")]
    assert with_default == with_empty
    assert len(with_default) == 39


def test_the_gate_verb_offers_the_flag():
    from context_lift.cli import _build_parser
    gate = _build_parser()._subparsers._group_actions[0].choices["gate"]
    assert gate.get_default("spec") is None      # declared, and off by default
    assert "--spec" in gate.format_help()
